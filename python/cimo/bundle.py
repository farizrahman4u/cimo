"""Single-file distribution: `cimo bundle` writes one `cimo.py` that works like the package.

The bundle holds every module's source and the package files (bundled headers, runtime
sources) as string literals in one table, `{path relative to the package: text}`, and a small
import hook that serves `cimo.*` modules from it. Imported as `cimo`, the file becomes the
package itself. cimo.resources reads headers and runtime sources from the same table. Only
sources: the runtime library is compiled on demand like everywhere else (cimo.linker).

The output is deterministic: files in sorted order, no timestamps.
"""

