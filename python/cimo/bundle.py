_ESCAPE = re.compile("[\\x00-\\x08\\x0b-\\x1f\\x7f\\ud800-\\udfff]|'(?='')|'\\Z")


def _escape(m):
    c = m.group()
    return "\\'" if c == "'" else '\\r' if c == '\r' else '\\x%02x' % ord(c) if ord(c) < 128 \
        else '\\u%04x' % ord(c)


def _literal(text):
    """`text` as a readable triple-quoted literal that evaluates back to it exactly."""
    lit = "'''\\\n" + _ESCAPE.sub(_escape, text.replace('\\', '\\\\')) + "'''"
    if ast.literal_eval(lit) != text:
        raise AssertionError('cannot embed text as a string literal')
    return lit


