_ESCAPE = re.compile("[\\x00-\\x08\\x0b-\\x1f\\x7f\\ud800-\\udfff]|'(?='')|'\\Z")


def _escape(m):
    c = m.group()
    return "\\'" if c == "'" else '\\r' if c == '\r' else '\\x%02x' % ord(c) if ord(c) < 128 \
        else '\\u%04x' % ord(c)


def _literal(text):
    """`text` as a readable triple-quoted literal that evaluates back to it exactly."""
    lit = "'''\\\n" + _ESCAPE.sub(_escape, text.replace('\\', '\\\\')) + "'''"
    if ast.literal_eval(lit) != text:
        raise AssertionError('cannot embed text as a string literal')
    return lit


def _package_files():
    """{path relative to the package: text} of the files the bundle embeds."""
    out = {}
    for p in _res.files(_res.ROOT, _EXTS):
        rel = os.path.relpath(p, _res.ROOT).replace(os.sep, '/')
        if not rel.startswith('prebuilt/'):
            out[rel] = _res.read_text(p)
    for rel in _EXTRA:
        out[rel] = _res.read_text(_res.path(rel))
    return out


def _prebuilt_runtime():
    """The compiled runtime as package files: prebuilt/runtime-<key>/ (see linker.runtime)."""
    from . import linker
    rt = linker.runtime()
    d = 'prebuilt/runtime-%s/' % rt.key
    out = {d + 'index.json': json.dumps(rt.index, indent=0, sort_keys=True)}
    for m in rt.index:
        out[d + linker.member_file(m)] = rt.text(m)
    return out


def _version():
    import cimo
    return getattr(cimo, '__version__', 'unknown')


def build(path='cimo.py', prebuilt=False, progress=None):
    """Write the single-file bundle to `path`. prebuilt: also embed the compiled runtime
    (built first if this process has not got it). progress(msg): status lines, optional.
    Returns stats: {'path', 'modules', 'resources', 'runtime_files', 'bytes',
    'runtime_bytes', 'seconds'}."""
    say = progress or (lambda msg: None)
    t0 = time.time()
    say('collecting package files from %s' % _res.ROOT)
    files = _package_files()
    runtime = {}
    if prebuilt:
        say('compiling the runtime library (cached after the first time)')
        runtime = _prebuilt_runtime()
        files.update(runtime)
    say('writing %s' % path)
    parts = [_HEADER.format(version=_version(), prebuilt=' --prebuilt' if prebuilt else '')]
    notices = _NOTICES + (('cproc (cimo/frontend)', files['frontend/LICENSE']),
                          ('QBE (cimo/backend)', files['backend/LICENSE']),
                          ('musl (cimo/runtime)', files['runtime/COPYRIGHT']))
    for name, text in notices:
        parts.append('# ' + '-' * 90 + '\n# ' + name + '\n#\n')
        parts.extend(('# ' + line).rstrip() + '\n' for line in text.splitlines())
        parts.append('#\n')
    parts.append('# ' + '-' * 90 + '\n\n')
    parts.append('_FILES = {\n')
    for rel in sorted(files):
        parts.append('%r: %s,\n' % (rel, _literal(files[rel])))
    parts.append('}\n')
    parts.append(_BOOTSTRAP)
    data = ''.join(parts).encode('utf-8')
    tmp = path + '.tmp%d' % os.getpid()
    with open(tmp, 'wb') as f:
        f.write(data)
    os.replace(tmp, path)
    stats = {
        'path': path,
        'modules': sum(rel.endswith('.py') for rel in files),
        'resources': sum(not rel.endswith('.py') for rel in files) - len(runtime),
        'runtime_files': len(runtime),
        'bytes': len(data),
        'runtime_bytes': sum(len(t.encode('utf-8')) for t in runtime.values()),
        'seconds': time.time() - t0,
    }
    say('wrote %s: %d modules, %d package files%s, %.1f MB in %.1f s' % (
        path, stats['modules'], stats['resources'],
        ', prebuilt runtime (%d files)' % len(runtime) if runtime else '',
        len(data) / 1e6, stats['seconds']))
    return stats
