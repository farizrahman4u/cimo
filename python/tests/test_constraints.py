@pytest.mark.parametrize('clause,src', REJECTED, ids=[c for c, _ in REJECTED])
def test_rejected(clause, src):
    with pytest.raises(cimo.CompileError) as ei:
        cimo.compile(src)
    msg = str(ei.value)
    assert LOC.match(msg) or re.match(r'^<string>:\d+: error: ', msg) \
        or msg.startswith("undefined symbol 'u'"), msg


@pytest.mark.parametrize('clause,src', WARNED, ids=[c for c, _ in WARNED])
def test_warned(clause, src, capfd):
    cimo.compile(src)
    assert ': warning: ' in capfd.readouterr().err


@pytest.mark.parametrize('clause,src,why', ACCEPTED, ids=[c for c, _, _ in ACCEPTED])
def test_accepted(clause, src, why):
    cimo.compile(src)
